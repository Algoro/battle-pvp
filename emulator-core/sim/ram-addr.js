// ram-addr.js — СЕМАНТИЧЕСКИЕ КОНСТАНТЫ адресов RAM, которые читает стек ИИ.
//
// Это единый источник правды для read-set: набор адресов, которые движки
// (game-view/GameState, tactical/planDefense, scan, lookahead) читают из RAM
// эмулятора при принятии решений. Любое расхождение между `sim.toMem()` и
// реальным RAM эмулятора по этим адресам означает, что ИИ в симуляторе
// видит «другой мир» и принимает другие решения (ai-eval != emu-eval).
//
// Соглашение об именах: адрес = семантическая роль (не голый номер),
// комментарий объясняет, что это значит в терминах игры.
//
// Память RAM: 0x00-0xFF — ноль-страница, 0x0100-0x01FF — стек/таймеры,
// 0x0400-0x07FF — буфер поля (тайлы 32x32).

// --- Состояние уровня / эффектов (однобайтовые флаги и таймеры) ---
export const RAM = {
  // Сколько врагов осталось убить до победы. 0xFF — игра ещё не началась.
  ENEMIES_LEFT: 0x80,
  // Таймер до появления следующего врага (уменьшается каждый кадр).
  SPAWN_TIMER: 0x82,
  // Лопата: >0 — база укреплена сталью (временный эффект).
  FORTIFIED: 0x45,
  // Часы: >0 — враги заморожены (не двигаются и не стреляют).
  CLOCK_TIMER: 0x0100,
  // Таймер бонуса: используется при появлении приза (не влияет на решения,
  // но нужен для полноты буфера, если движок читает его).
  BONUS_TIMER: 0x62,

  // --- Танки (8 штук, индекс i = 0..7) ---
  // 0,1 — защитники (игроки); 2..7 — враги (атакующие).
  // Каждое поле начинается с базового адреса и сдвигается на индекс танка.
  TANK_X: 0x90,     // +i: координата X танка (пиксель)
  TANK_Y: 0x98,     // +i: координата Y танка
  TANK_FLAG: 0xa0,  // +i: флаг-машина танка (0x00 мёртв, 0xa0|dir движение,
                    //     0x73 взрыв, 0xe0+ респавн, 0x80 блок)
  TANK_TYPE: 0xa8,  // +i: тип танка (0x80 обычный, 0xa0, 0xc0, 0xe0 + броня/флеш)
  HELMET: 0x89,     // +i: каска (неуязвимость) — ТОЛЬКО защитники (i<2)
  STUN: 0x6f,       // +i: ошеломление (не может двигаться) — ТОЛЬКО защитники

  // --- Пули (8 слотов, индекс i = 0..7; слот i принадлежит танку i) ---
  BULLET_STATUS: 0xcc, // +i: статус пули (0x40|dir — летит, 0x33 — взрыв, 0x00 — нет)
  BULLET_X: 0xb8,      // +i: координата X пули
  BULLET_Y: 0xc2,      // +i: координата Y пули

  // --- Приз (бонус) ---
  PRIZE_ID: 0x88,   // id приза (0xff — нет приза)
  PRIZE_X: 0x86,    // координата X приза
  PRIZE_Y: 0x87,    // координата Y приза

  // --- Поле ---
  FIELD: 0x0400,    // буфер тайлов 32x32 = 1024 байта (0x0400..0x07FF)
};

// Размер поля в тайлах (по ширине/высоте).
export const FIELD_SIZE = 32;

