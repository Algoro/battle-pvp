// sub_E902_convert_random_number_to_position (ASM E902-E90F):
//   $00 = A (0-3); ASL; ADC $00; ASL; ADC #$06; ASL; ASL; ASL
//   => ((A*2 + A)*2 + 6) * 8 = (A*6 + 6) * 8 = (A+1)*48
//   => 0->0x30(48), 1->0x60(96), 2->0x90(144), 3->0xC0(192).
// (Проверено PC-хуком sub_E902 и бисекцией: приз в эмуляторе в (96,144), не (72,120).)
export function bonusPosFromRng(v) { return (v + 1) * 48; }

