#!/bin/bash
# =============================================================================
# commands-for-user.sh — команды, требующие root (sudo), которые агент не может
# выполнить сам в user-space. Всё остальное окружение развёрнуто без sudo.
# Запускать вручную, под пользователем с правами sudo, затем перелогиниться.
# Относительный путь: ./reports/commands-for-user.sh
# =============================================================================

set -e

echo "=============================================================="
echo " [1/2] Docker (для контейнеризации backend). НЕ обязателен сейчас:"
echo "       backend разрабатывается и гоняется прямым Node-процессом"
echo "       с SQLite до появления Docker. Выполнить при необходимости."
echo "=============================================================="
sudo apt update
sudo apt install -y git build-essential curl wget unzip cmake pkg-config
curl -fsSL https://get.docker.com | sudo sh
sudo usermod -aG docker $USER

echo "=============================================================="
echo " [2/2] ВАЖНО: после добавления в группу docker нужно"
echo "       ПЕРЕЛОГИНИТЬСЯ (log out/in или новый терминал), чтобы"
echo "       группа применилась, затем проверить:"
echo "         docker run hello-world"
echo "=============================================================="

echo
echo "Проверка после перелогина:"
echo "  groups              # должен содержать 'docker'"
echo "  docker run hello-world"
